def number(value, digits=2):
    if isinstance(value,str):
        return value
    if pd.isna(value):
        return "ناموجود"
    return f"{value:,.{digits}f}".translate(str.maketrans("0123456789.,","۰۱۲۳۴۵۶۷۸۹٫٬"))


def md_table(headers, rows):
    return "\n".join(["| "+" | ".join(headers)+" |",
                      "|"+"|".join("---" for _ in headers)+"|",
                      *["| "+" | ".join(map(str,row))+" |" for row in rows]])


class PDF:
    def __init__(self, path):
        self.pdf = PdfPages(path)
        self.pdf.infodict().update(Title="Phase 2 - Reviewer genre preferences", Author="DA project")
        self.fig = None
        self.page = 0
        self.title = ""

    def new(self,title):
        if self.fig is not None:
            self.pdf.savefig(self.fig)
            plt.close(self.fig)
        self.title = title
        self.page += 1
        self.fig = plt.figure(figsize=(8.27,11.69),facecolor="white")
        self.fig.text(.91,.955,"پروژهٔ تحلیل داده | فاز دوم",ha="right",color=TEAL,fontsize=10)
        self.fig.text(.91,.907,title,ha="right",color=INK,fontsize=18,weight="bold")
        self.fig.text(.09,.035,"Amazon Reviews'23 / Books",fontsize=8,color="#5E7480")
        self.fig.text(.91,.035,number(self.page,0),ha="right",fontsize=8,color="#5E7480")
        self.y = .865

    def ensure(self,height):
        if self.y-height < .075:
            self.new(self.title)

    def paragraph(self,text):
        lines = textwrap.wrap(text, width=91, break_long_words=False,break_on_hyphens=False)
        self.ensure(len(lines)*.019+.017)
        for line in lines:
            self.fig.text(.91,self.y,line,ha="right",va="top",fontsize=10.4,color=INK)
            self.y -= .019
        self.y -= .017

    def table(self,headers,rows):
        if len(rows)>18:
            for start in range(0,len(rows),18):
                self.table(headers,rows[start:start+18])
            return
        # Reverse columns so the first field is at the right edge.
        lengths = [min(38,max(8,max(len(str(row[j])) for row in [headers,*rows]))) for j in range(len(headers))]
        widths = np.asarray(lengths)/sum(lengths)
        def wrap_row(row):
            wrapped = []
            for value,width in zip(row,widths):
                lines = textwrap.wrap(str(value),width=max(8,int(120*width)),break_long_words=False)
                wrapped.append("\n".join(lines))
            return wrapped
        wrapped_rows = [wrap_row(row) for row in [headers,*rows]]
        heights = [max(s.count("\n")+1 for s in row)*.017+.013 for row in wrapped_rows]
        height = sum(heights)
        self.ensure(height+.03)
        ax = self.fig.add_axes([.09,self.y-height,.82,height])
        ax.axis("off")
        cells = [row[::-1] for row in wrapped_rows[1:]]
        grid = ax.table(cellText=cells,colLabels=wrapped_rows[0][::-1],
                        colWidths=widths[::-1],cellLoc="center",bbox=[0,0,1,1])
        grid.auto_set_font_size(False)
        grid.set_fontsize(8.2)
        for (row,col),cell in grid.get_celld().items():
            cell.set_height(heights[row]/height)
            cell.set_edgecolor("white")
            cell.set_facecolor(TEAL if row==0 else ("#EFF5F5" if row%2 else "#FAFBFC"))
            cell.set_text_props(color="white" if row==0 else INK,weight="bold" if row==0 else "normal")
        self.y -= height+.028

    def image(self,name):
        path = PUB/name
        with Image.open(path) as im:
            ratio = im.height/im.width
        height = min(.36,.82*8.27/11.69*ratio)
        self.ensure(height+.025)
        ax = self.fig.add_axes([.08,self.y-height,.84,height])
        ax.imshow(plt.imread(path))
        ax.axis("off")
        self.y -= height+.025

    def close(self):
        if self.fig is not None:
            self.pdf.savefig(self.fig)
            plt.close(self.fig)
        self.pdf.close()


